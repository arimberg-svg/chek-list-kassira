JS = r"""
  (function () {
    const KEY = "__KEY__";
    const root = document.getElementById("checklist");
    const status = document.getElementById("save-status");
    const fields = () => root.querySelectorAll("[data-k]");
    function assignIds() {
      fields().forEach((el, i) => { if (!el.dataset.id) el.dataset.id = "f" + i; });
    }
    function collect() {
      const data = {};
      fields().forEach((el) => {
        data[el.dataset.id] = el.type === "checkbox" ? el.checked : el.value;
      });
      return data;
    }
    function apply(data) {
      if (!data) return;
      fields().forEach((el) => {
        const id = el.dataset.id;
        if (!(id in data)) return;
        if (el.type === "checkbox") el.checked = !!data[id];
        else el.value = data[id] || "";
      });
    }
    function save(manual) {
      try {
        localStorage.setItem(KEY, JSON.stringify(collect()));
        const t = new Date();
        status.textContent = (manual ? "сохранено " : "автосохранение ") +
          t.toLocaleTimeString("ru-RU", { hour: "2-digit", minute: "2-digit" });
      } catch (e) {
        status.textContent = "не удалось сохранить";
      }
    }
    function load() {
      try {
        const raw = localStorage.getItem(KEY);
        if (raw) apply(JSON.parse(raw));
      } catch (e) {}
    }
    assignIds();
    load();
    let timer;
    root.addEventListener("input", () => {
      clearTimeout(timer);
      timer = setTimeout(() => save(false), 400);
    });
    root.addEventListener("change", () => save(false));
    document.getElementById("btn-save").addEventListener("click", () => save(true));
    document.getElementById("btn-print").addEventListener("click", () => { save(true); window.print(); });
    document.getElementById("btn-clear").addEventListener("click", () => {
      if (!confirm("Очистить все отметки и поля в этом браузере?")) return;
      fields().forEach((el) => {
        if (el.type === "checkbox") el.checked = false;
        else el.value = "";
      });
      localStorage.removeItem(KEY);
      status.textContent = "очищено";
    });
  })();
"""


