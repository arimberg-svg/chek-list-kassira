ROOT = Path(__file__).resolve().parent


def esc(s):
    return html.escape(s, quote=True)


def item(text, steps=None):
    body = f'<span class="proc">{esc(text)}</span>' if steps else esc(text)
    if steps:
        lis = "".join(f"<li>{esc(s)}</li>" for s in steps)
        body += f'<ul class="steps">{lis}</ul>'
    return (
        '<label class="item">'
        '<input type="checkbox" data-k />'
        '<span class="box" aria-hidden="true"></span>'
        f'<span class="txt">{body}</span>'
        "</label>"
    )


def items(texts):
    out = []
    for t in texts:
        if isinstance(t, tuple):
            out.append(item(t[0], t[1]))
        else:
            out.append(item(t))
    return "\n".join(out)


def block(title, texts, note=""):
    note_html = f'<p class="when">{esc(note)}</p>' if note else ""
    return (
        '<section class="block">'
        f"<h2>{esc(title)}</h2>"
        f"{note_html}"
        f'<div class="list">{items(texts)}</div>'
        "</section>"
    )


def field(label):
    return (
        '<label class="field">'
        f"<span>{esc(label)}</span>"
        '<input type="text" data-k class="ink" autocomplete="off" />'
        "</label>"
    )


def fields(labels):
    return "\n".join(field(x) for x in labels)


