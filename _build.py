def esc(s):
    return html.escape(s, quote=True)


def item(text, steps=None):
    body = f'<span class="proc">{esc(text)}</span>' if steps else esc(text)
    if steps:
        lis = "".join(f"<li>{esc(s)}</li>" for s in steps)
        body += f'<ul class="steps">{lis}</ul>'
    return (
        '<label class="item">'
        '<input type="checkbox" data-k />'
        '<span class="box" aria-hidden="true"></span>'
        f'<span class="txt">{body}</span>'
        "</label>"
    )


def items(texts):
    out = []
    for t in texts:
        if isinstance(t, tuple):
            out.append(item(t[0], t[1]))
        else:
            out.append(item(t))
    return "\n".join(out)


def note_lines():
    return (
        '<div class="lines"><span>Заметки</span>'
        '<input type="text" data-k class="ink" autocomplete="off" />'
        '<input type="text" data-k class="ink" autocomplete="off" />'
        "</div>"
    )


def block(title, texts, note="", notes=False):
    note_html = f'<p class="when">{esc(note)}</p>' if note else ""
    cls = "block day" if "2026" in title else "block"
    extra = note_lines() if notes else ""
    return (
        f'<section class="{cls}">'
        f"<h2>{esc(title)}</h2>"
        f"{note_html}"
        f'<div class="list">{items(texts)}</div>'
        f"{extra}"
        "</section>"
    )


def study(title, steps):
    lis = "".join(f"<li>{esc(s)}</li>" for s in steps)
    return (
        '<section class="block">'
        f"<h2>{esc(title)}</h2>"
        f'<ul class="steps plain">{lis}</ul>'
        '<div class="marks">'
        '<label class="choice"><input type="checkbox" data-k /> Изучил</label>'
        '<label class="choice"><input type="checkbox" data-k /> Понял</label>'
        "</div>"
        '<div class="lines"><span>Запись</span>'
        '<input type="text" data-k class="ink" autocomplete="off" />'
        '<input type="text" data-k class="ink" autocomplete="off" />'
        "</div>"
        "</section>"
    )


def field(label):
    return (
        '<label class="field">'
        f"<span>{esc(label)}</span>"
        '<input type="text" data-k class="ink" autocomplete="off" />'
        "</label>"
    )


def fields(labels):
    return "\n".join(field(x) for x in labels)


